test("research asset route rejects traversal and non-PNG or directory targets", async (t) => {
  const app = await startResearchServer();
  t.after(() => app.close());

  for (const path of [
    "/research-assets/../secret.png",
    "/research-assets/%2e%2e%2fsecret.png",
    "/research-assets/dev%5csecret.png",
    "/research-assets/dev/calibration/readme.txt",
    "/research-assets/dev/calibration/",
  ]) {
    const response = await rawRequest(app.baseUrl, path);
    assert.equal(response.status, 403, path);
    assert.equal(JSON.parse(response.body).error.code, "research_asset_forbidden", path);
  }
});

test("research asset route hides unlisted, missing, and directory targets", async (t) => {
  const app = await startResearchServer();
  t.after(() => app.close());

  const unlistedPath = join(app.researchRoot, "fixtures", "unlisted.png");
  await writeFile(unlistedPath, PNG_BYTES);
  const unlisted = await fetch(`${app.baseUrl}/research-assets/unlisted.png`);
  assert.equal(unlisted.status, 404);
  assert.equal((await responseJson(unlisted)).error.code, "research_asset_not_found");

  const missingUrl = app.catalog.fixtures[0].assets.foreground;
  const missingPath = join(
    app.researchRoot,
    "fixtures",
    ...missingUrl.slice("/research-assets/".length).split("/"),
  );
  await rm(missingPath);
  const missing = await fetch(`${app.baseUrl}${missingUrl}`);
  assert.equal(missing.status, 404);
  assert.equal((await responseJson(missing)).error.code, "research_asset_not_found");

  const directoryUrl = app.catalog.fixtures[0].assets.compositeBlack;
  const directoryPath = join(
    app.researchRoot,
    "fixtures",
    ...directoryUrl.slice("/research-assets/".length).split("/"),
  );
  await rm(directoryPath);
  await mkdir(directoryPath);
  const directory = await fetch(`${app.baseUrl}${directoryUrl}`);
  assert.equal(directory.status, 404);
  assert.equal((await responseJson(directory)).error.code, "research_asset_not_found");
});

test("research asset route rejects an allowlisted symlink that escapes fixtures", async (t) => {
  const app = await startResearchServer();
  t.after(() => app.close());

  const assetUrl = app.catalog.fixtures[0].assets.source;
  const assetPath = join(
    app.researchRoot,
    "fixtures",
    ...assetUrl.slice("/research-assets/".length).split("/"),
  );
  const outsidePath = join(app.root, `outside-${randomUUID()}.png`);
  await writeFile(outsidePath, PNG_BYTES);
  await rm(assetPath);
  try {
    await symlink(outsidePath, assetPath, "file");
  } catch (error) {
    if (error?.code === "EPERM" || error?.code === "EACCES") {
      const fixtureDirectory = dirname(assetPath);
      const outsideDirectory = join(app.root, `outside-${randomUUID()}`);
      await mkdir(outsideDirectory);
      await writeFile(join(outsideDirectory, "source.png"), PNG_BYTES);
      await rm(fixtureDirectory, { recursive: true, force: true });
      try {
        await symlink(outsideDirectory, fixtureDirectory, "junction");
      } catch (junctionError) {
        if (junctionError?.code === "EPERM" || junctionError?.code === "EACCES") {
          t.skip("This environment does not permit creating a symlink or junction");
          return;
        }
        throw junctionError;
      }
    } else {
      throw error;
    }
  }

  const response = await fetch(`${app.baseUrl}${assetUrl}`);
  assert.equal(response.status, 403);
  assert.equal((await responseJson(response)).error.code, "research_asset_forbidden");
});

test("missing and invalid research catalogs share a non-disclosing error", async (t) => {
  const missingApp = await startResearchServer({ writeCatalog: false });
  t.after(() => missingApp.close());
  const missing = await fetch(`${missingApp.baseUrl}/api/research/fixtures`);
  assert.equal(missing.status, 503);
  const missingBody = await responseJson(missing);
  assert.deepEqual(missingBody.error, {
    code: "research_catalog_unavailable",
    message: "研究夹具清单不可用",
    requestId: null,
  });
  assert.equal(JSON.stringify(missingBody).includes(missingApp.root), false);

  const invalidApp = await startResearchServer();
  t.after(() => invalidApp.close());
  await writeFile(invalidApp.catalogPath, "{invalid-json");
  const invalid = await fetch(`${invalidApp.baseUrl}/api/research/fixtures`);
  assert.equal(invalid.status, 503);
  assert.deepEqual((await responseJson(invalid)).error, missingBody.error);
});

test("catalog validation fails closed on visibility, unknown fields, or allowlist mismatch", async () => {
  const privateCatalog = makeCatalog();
  privateCatalog.fixtures[0].visibility = "private-user";

  const unknownFieldCatalog = makeCatalog();
  unknownFieldCatalog.unexpected = true;

  const mismatchedCatalog = makeCatalog();
  mismatchedCatalog.assetAllowlist.push(
    "/research-assets/dev/calibration/MATTE-GT/fixture-01/unreferenced.png",
  );
  mismatchedCatalog.assetAllowlist.sort();

  const emptyFixturesWithAssets = makeCatalog();
  emptyFixturesWithAssets.fixtures = [];

  const fixturesWithoutAssets = makeCatalog();
  fixturesWithoutAssets.assetAllowlist = [];

  for (const catalog of [
    privateCatalog,
    unknownFieldCatalog,
    mismatchedCatalog,
    emptyFixturesWithAssets,
    fixturesWithoutAssets,
  ]) {
    const app = await startResearchServer({ catalog });
    try {
      const response = await fetch(`${app.baseUrl}/api/research/fixtures`);
      assert.equal(response.status, 503);
      assert.equal((await responseJson(response)).error.code, "research_catalog_unavailable");
    } finally {
      await app.close();
    }
  }
});
