const PNG_BYTES = Buffer.from([137, 80, 78, 71, 13, 10, 26, 10, 0, 0, 0, 0]);
const ASSET_NAMES = [
  "source",
  "alpha",
  "foreground",
  "compositeBlack",
  "compositeWhite",
  "compositeSaturated",
];
const ASSET_FILES = {
  source: "source.png",
  alpha: "alpha.png",
  foreground: "foreground.png",
  compositeBlack: "composite-black.png",
  compositeWhite: "composite-white.png",
  compositeSaturated: "composite-saturated.png",
};

function makeCatalog() {
  const assetBase = "/research-assets/dev/calibration/MATTE-GT/fixture-01";
  const assets = Object.fromEntries(
    ASSET_NAMES.map((name) => [name, `${assetBase}/${ASSET_FILES[name]}`]),
  );
  return {
    schemaVersion: "review-catalog.v0",
    catalogId: "catalog-test",
    catalogVersion: "0.0.1",
    generatedAt: "2026-08-15T00:00:00.000Z",
    evidenceStatus: { level: "C1=0", purpose: "method-rehearsal" },
    visibilityPolicy: { allowed: ["public-synthetic"] },
    assetAllowlist: Object.values(assets).sort(),
    fixtures: [{
      id: "fixture-01",
      label: "Synthetic fixture 01",
      suite: "MATTE-GT",
      partition: "dev/calibration",
      sourceRevision: "generator-test@1",
      candidateAlias: "candidate-a",
      methodLabel: "synthetic ground truth",
      methodDetails: "Generated by the test-only deterministic fixture helper.",
      rightsRecordId: "rights.synthetic.test",
      visibility: "public-synthetic",
      evidenceStatus: { level: "C1=0", purpose: "method-rehearsal" },
      assets,
      facts: {
        category: "synthetic-shape",
        edgeType: "hard",
        expectedUse: "server contract test",
      },
    }],
  };
}

async function startResearchServer({
  catalog = makeCatalog(),
  previewMode = "local",
  writeCatalog = true,
} = {}) {
  const root = await mkdtemp(join(tmpdir(), "single-image-research-server-"));
  const webRoot = join(root, "web");
  const researchRoot = join(root, "research");
  const catalogPath = join(researchRoot, "manifests", "review-catalog.v0.json");
  await mkdir(webRoot, { recursive: true });
  await writeFile(join(webRoot, "index.html"), "<!doctype html><title>R0</title>");

  if (writeCatalog) {
    await mkdir(dirname(catalogPath), { recursive: true });
    await writeFile(catalogPath, JSON.stringify(catalog));
    for (const assetUrl of catalog.assetAllowlist ?? []) {
      if (typeof assetUrl !== "string" || !assetUrl.startsWith("/research-assets/")) continue;
      const target = join(
        researchRoot,
        "fixtures",
        ...assetUrl.slice("/research-assets/".length).split("/"),
      );
      await mkdir(dirname(target), { recursive: true });
      await writeFile(target, PNG_BYTES);
    }
  }

  const app = createImageStudioServer({
    apiKey: "",
    previewMode,
    webRoot,
    researchRoot,
    researchCatalogPath: catalogPath,
  });
  await new Promise((resolve, reject) => {
    app.server.once("error", reject);
    app.server.listen(0, "127.0.0.1", resolve);
  });
  const address = app.server.address();
  return {
    ...app,
    baseUrl: `http://127.0.0.1:${address.port}`,
    root,
    researchRoot,
    catalogPath,
    catalog,
    async close() {
      await new Promise((resolve, reject) => app.server.close((error) => error ? reject(error) : resolve()));
      await rm(root, { recursive: true, force: true });
    },
  };
}

async function responseJson(response) {
  return JSON.parse(await response.text());
}

async function rawRequest(origin, path, method = "GET") {
  const url = new URL(origin);
  return new Promise((resolve, reject) => {
    const request = httpRequest({
      hostname: url.hostname,
      port: url.port,
      path,
      method,
    }, (response) => {
      const chunks = [];
      response.on("data", (chunk) => chunks.push(chunk));
      response.on("end", () => resolve({
        status: response.statusCode,
        headers: response.headers,
        body: Buffer.concat(chunks),
      }));
    });
    request.on("error", reject);
    request.end();
  });
}

test("local preview serves the validated research catalog and allowlisted PNG", async (t) => {
  const app = await startResearchServer();
  t.after(() => app.close());

  const catalogResponse = await fetch(`${app.baseUrl}/api/research/fixtures`);
  assert.equal(catalogResponse.status, 200);
  assert.equal(catalogResponse.headers.get("cache-control"), "no-store");
  assert.equal(catalogResponse.headers.get("content-type"), "application/json; charset=utf-8");
  assert.deepEqual(await responseJson(catalogResponse), app.catalog);

  const assetUrl = app.catalog.fixtures[0].assets.source;
  const assetResponse = await fetch(`${app.baseUrl}${assetUrl}`);
  assert.equal(assetResponse.status, 200);
  assert.equal(assetResponse.headers.get("content-type"), "image/png");
  assert.equal(assetResponse.headers.get("cache-control"), "no-store");
  assert.equal(assetResponse.headers.get("x-content-type-options"), "nosniff");
  assert.deepEqual(Buffer.from(await assetResponse.arrayBuffer()), PNG_BYTES);
});

test("local preview serves a valid empty research catalog with HTTP 200", async (t) => {
  const catalog = makeCatalog();
  catalog.fixtures = [];
  catalog.assetAllowlist = [];
  const app = await startResearchServer({ catalog });
  t.after(() => app.close());

  const response = await fetch(`${app.baseUrl}/api/research/fixtures`);
  assert.equal(response.status, 200);
  assert.equal(response.headers.get("cache-control"), "no-store");
  assert.deepEqual(await responseJson(response), catalog);
});

test("research PNG supports HEAD without returning a response body", async (t) => {
  const app = await startResearchServer();
  t.after(() => app.close());

  const assetUrl = app.catalog.fixtures[0].assets.alpha;
  const response = await fetch(`${app.baseUrl}${assetUrl}`, { method: "HEAD" });
  assert.equal(response.status, 200);
  assert.equal(response.headers.get("content-type"), "image/png");
  assert.equal(response.headers.get("cache-control"), "no-store");
  assert.equal(Number(response.headers.get("content-length")), PNG_BYTES.length);
  assert.equal((await response.arrayBuffer()).byteLength, 0);
});

